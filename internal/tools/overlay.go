var overlayDir = sync.OnceValue(func() string {
	if dir := os.Getenv("IRIS_SCREENSHOT_DIR"); dir != "" {
		return dir
	}
	cacheDir, err := os.UserCacheDir()
	if err != nil {
		return "screenshots"
	}
	return filepath.Join(cacheDir, "iris")
})

func saveVerifyOverlay(logger *slog.Logger, screenshotB64 string, imgW, imgH int, bbox BoundingBox, answer, evidence string) {
	rgba, err := decodeOverlayImage(logger, screenshotB64, "verify overlay")
	if err != nil {
		return
	}

	boxColor := color.RGBA{0, 200, 0, 255}
	if answer != "yes" {
		boxColor = color.RGBA{255, 0, 0, 255}
	}

	if bbox.X2 > bbox.X1 && bbox.Y2 > bbox.Y1 {
		drawThickRect(rgba, image.Rect(bbox.X1, bbox.Y1, bbox.X2, bbox.Y2), 4, boxColor)
	}

	label := fmt.Sprintf("VLM: %s | %s", answer, evidence)
	if len(label) > 80 {
		label = label[:80] + "..."
	}
	labelY := bbox.Y1 - 28
	if labelY < 2 {
		labelY = bbox.Y2 + 4
	}
	drawLabelBG(rgba, 2, labelY, len(label)*7+8, 24, color.RGBA{0, 0, 0, 200})
	for i, ch := range label {
		drawChar(rgba, 4+i*7, labelY+4, ch, boxColor)
	}

	ts := time.Now().Format("20060102-150405")
	filename := fmt.Sprintf("verify-%s-%dx%d-%s.png", ts, imgW, imgH, answer)
	saveOverlayFile(logger, rgba, filename, "verify overlay")
}

func decodeOverlayImage(logger *slog.Logger, screenshotB64, tag string) (*image.RGBA, error) {
	dir := overlayDir()
	if err := os.MkdirAll(dir, 0o750); err != nil {
		logger.Debug(tag+": could not create dir", "dir", dir, "error", err)
		return nil, err
	}

	pngData, err := base64.StdEncoding.DecodeString(screenshotB64)
	if err != nil {
		logger.Debug(tag+": base64 decode failed", "error", err)
		return nil, err
	}

	srcImg, _, err := image.Decode(bytes.NewReader(pngData))
	if err != nil {
		logger.Debug(tag+": image decode failed", "error", err)
		return nil, err
	}

	rgba, ok := srcImg.(*image.RGBA)
	if !ok {
		rgba = image.NewRGBA(srcImg.Bounds())
		draw.Draw(rgba, rgba.Bounds(), srcImg, srcImg.Bounds().Min, draw.Src)
	}
	return rgba, nil
}

func saveOverlayFile(logger *slog.Logger, rgba *image.RGBA, filename, tag string) {
	dir := overlayDir()
	path := filepath.Join(dir, filename)
	f, err := os.Create(path)
	if err != nil {
		logger.Debug(tag+": could not create file", "path", path, "error", err)
		return
	}
	defer f.Close()
	if err := png.Encode(f, rgba); err != nil {
		logger.Debug(tag+": png encode failed", "error", err)
		return
	}
	fi, statErr := f.Stat()
	fileSize := int64(0)
	if statErr == nil {
		fileSize = fi.Size()
	}
	logger.Info(tag+" saved", "path", path, "file_size_bytes", fileSize)
}

func drawThickRect(dst *image.RGBA, rect image.Rectangle, thickness int, c color.Color) {
	for i := range thickness {
		draw.Draw(dst, image.Rect(rect.Min.X-i, rect.Min.Y-i, rect.Max.X+i, rect.Min.Y-i+1), &image.Uniform{C: c}, image.Point{}, draw.Src)
		draw.Draw(dst, image.Rect(rect.Min.X-i, rect.Max.Y+i-1, rect.Max.X+i, rect.Max.Y+i), &image.Uniform{C: c}, image.Point{}, draw.Src)
		draw.Draw(dst, image.Rect(rect.Min.X-i, rect.Min.Y-i, rect.Min.X-i+1, rect.Max.Y+i), &image.Uniform{C: c}, image.Point{}, draw.Src)
		draw.Draw(dst, image.Rect(rect.Max.X+i-1, rect.Min.Y-i, rect.Max.X+i, rect.Max.Y+i), &image.Uniform{C: c}, image.Point{}, draw.Src)
	}
}

func drawLabelBG(dst *image.RGBA, x, y, w, h int, c color.Color) {
	draw.Draw(dst, image.Rect(x, y, x+w, y+h), &image.Uniform{C: c}, image.Point{}, draw.Src)
}

func drawChar(dst *image.RGBA, x, y int, ch rune, c color.Color) {
	glyph, ok := overlayFont[ch]
	if !ok {
		return
	}
	for row := range 12 {
		for col := range 7 {
			if glyph[row]&(1<<(6-col)) != 0 {
				px := x + col
				py := y + row
				if px >= dst.Bounds().Min.X && px < dst.Bounds().Max.X && py >= dst.Bounds().Min.Y && py < dst.Bounds().Max.Y {
					dst.Set(px, py, c)
				}
			}
		}
	}
}

